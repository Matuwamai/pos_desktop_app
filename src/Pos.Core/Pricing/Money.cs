namespace Pos.Core.Pricing;

/// <summary>
/// Rounding to a currency's own minor-unit precision (<see cref="CurrencyInfo"/> decides
/// how many decimal places that is — 2 for the vast majority, 0 for JPY-style currencies),
/// matching the server's <c>round()</c> (<c>server/utils/money.js</c>:
/// <c>Math.round(n * factor) / factor</c>).
///
/// The server rounds a JS <c>double</c>; this rounds a <c>decimal</c>, which has no binary
/// floating-point representation error. For every tax rate this business actually uses
/// (0%, 8%, 16%) the two methods agree to the cent, and the golden fixtures in
/// <c>tests/Pos.Tests/Fixtures/pricing-golden.json</c> (generated by running the server's own
/// function, all at 2 decimal places) are the proof.
///
/// They do *not* agree for every possible rate: <c>PricingMathTests.FloatRoundingDivergence_*</c>
/// records a confirmed case at 17.5% where the server's float math lands a cent low on an exact
/// half-cent tie (0.175 isn't exactly representable in binary, so <c>subtotal * 0.175</c> comes
/// out a hair under the true value before <c>Math.round</c> ever sees it). That is a server bug,
/// not a fixture problem — decimal's 0.53 is the mathematically correct round-half-away-from-zero
/// answer, the server's 0.52 is a float artifact — but fixing <c>round2()</c> (duplicated across
/// order.js/invoice.js/offlineSync.js) is a cross-cutting change to live pricing math that needs
/// sign-off, not something to do silently from the desktop side. Flagged for the user; until then,
/// 17.5% (and any other rate whose binary expansion isn't exact) is excluded from the golden set.
/// </summary>
public static class Money
{
    public static decimal Round(decimal value, int decimalDigits) => Math.Round(value, decimalDigits, MidpointRounding.AwayFromZero);
}
