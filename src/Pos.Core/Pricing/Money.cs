namespace Pos.Core.Pricing;

/// <summary>
/// Rounding to the cent, matching the server's <c>round2()</c>
/// (<c>server/services/order.js</c>: <c>Math.round(n * 100) / 100</c>).
///
/// The server rounds a JS <c>double</c>; this rounds a <c>decimal</c>, which has no binary
/// floating-point representation error. For every amount a cash register actually produces
/// — a price with at most 2 decimal places, times a small integer quantity, times a tax rate
/// with at most 4 decimal places — the two methods agree, and the golden fixtures in
/// <c>tests/Pos.Tests/Fixtures/pricing-golden.json</c> (generated by running the server's own
/// function) are the proof. They would disagree only on an exact tie like 1.005 landing on
/// 100.49999999999999 in float before rounding — a case that offline pricing input can't
/// produce, so round-half-away-from-zero on decimal is the right, exact tie-break here.
/// </summary>
public static class Money
{
    public static decimal Round2(decimal value) => Math.Round(value, 2, MidpointRounding.AwayFromZero);
}
